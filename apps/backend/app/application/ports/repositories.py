from __future__ import annotations

from typing import Protocol

from ...domain.assessment.models import Response
from ...domain.student.models import Student
from ...domain.subject.models import LearningObjective
from ...domain.teaching.models import TeacherReview


class AnalysisRuns(Protocol):
    def current(self) -> dict: ...
    def load(self, run_id: str) -> dict: ...
    def load_snapshot(self, run_id: str) -> str: ...
    def save(self, run: dict) -> None: ...
    def save_snapshot(
        self, snapshot_text: str, *, set_current: bool = True
    ) -> None: ...
    def list_run_ids(self) -> list[str]: ...
    def set_current(self, run_id: str) -> None: ...
    def projection_counts(self, run_id: str) -> dict[str, int]: ...


class ReviewHistories(Protocol):
    def list(self, run_id: str) -> dict: ...
    def append(self, run_id: str, key: str, payload: dict) -> dict: ...
    def list_domain(
        self, run_id: str, student_id: str, indicator_id: str
    ) -> list[TeacherReview]: ...
    def import_history(self, run_id: str, history: dict) -> int: ...


class Stage2Records(Protocol):
    def list_sources(self, run_id: str) -> dict[str, list[dict]]: ...
    def list_cases(self, run_id: str) -> dict[str, list[dict]]: ...
    def append_source(self, run_id: str, indicator_id: str, payload: dict) -> dict: ...
    def append_case(self, run_id: str, student_id: str, payload: dict) -> dict: ...


class TeachingAdjustments(Protocol):
    def list(self, student_id: str | None = None) -> list[dict]: ...
    def get(self, adjustment_id: str) -> dict | None: ...
    def create(self, origin: dict, payload: dict) -> dict: ...
    def update(self, adjustment_id: str, payload: dict) -> dict: ...


class Students(Protocol):
    def get_by_id(self, run_id: str, student_id: str) -> Student | None: ...
    def list_by_class(self, run_id: str, class_id: str) -> list[Student]: ...
    def save(self, run_id: str, student: Student, class_group=None) -> None: ...


class Subjects(Protocol):
    def get_objective(
        self, run_id: str, indicator_id: str
    ) -> LearningObjective | None: ...
    def list_materials_for_objective(self, run_id: str, indicator_id: str) -> list: ...
    def get_assessment_item(self, run_id: str, material_id: str): ...


class Responses(Protocol):
    def get_by_id(self, run_id: str, record_id: str) -> Response | None: ...
    def list_by_student(
        self, run_id: str, student_id: str, *, selected_only: bool = False
    ) -> list[Response]: ...
    def save(self, run_id: str, response: Response) -> None: ...


DomainReviews = ReviewHistories
